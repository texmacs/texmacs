#!/usr/bin/env python3
"""Generate TeXmacs/progs/language/unicode-names.scm, the table which gives
the code point and the Unicode name of a TeXmacs symbol.

The symbols and their code points come from the conversion tables of
TeXmacs/langs/encoding; the names come from the unicodedata module of
Python, that is from the Unicode database of the interpreter which runs
this script.

usage: python3 tests/opentype/unicode-names.py [-o FILE]
"""

import argparse, os, re, sys, unicodedata

TABLES = ["tmuniversaltounicode.scm", "tmuniversaltounicode-extra.scm",
          "symbol-unicode-oneway.scm", "symbol-unicode-math.scm",
          "symbol-unicode-fallback.scm"]

def top ():
    return os.path.dirname (os.path.dirname (os.path.dirname (
        os.path.abspath (__file__))))

def load_codes ():
    "every TeXmacs symbol of the conversion tables, with its code points"
    codes = {}
    for name in TABLES:
        path = os.path.join (top (), "TeXmacs", "langs", "encoding", name)
        if not os.path.exists (path): continue
        for m in re.finditer (r'\("(<[^"]+>)"\s+"([^"]+)"\)', open (path).read ()):
            sym, val = m.group (1), m.group (2)
            cps = re.findall (r'#([0-9A-Fa-f]+)', val)
            if not cps or len (cps) != val.count ('#'): continue
            codes.setdefault (sym, [int (c, 16) for c in cps])
    return codes

def describe (cps):
    "U+0041 LATIN CAPITAL LETTER A, or the like for a composed symbol"
    pts = " ".join ("U+%04X" % c for c in cps)
    names = []
    for c in cps:
        try: names.append (unicodedata.name (chr (c)))
        except ValueError: names.append ("")
    names = [n for n in names if n != ""]
    if not names: return pts
    return pts + " " + ", ".join (names)

HEAD = '''\
;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;
;;
;; MODULE      : unicode-names.scm
;; DESCRIPTION : the code point and the Unicode name of a TeXmacs symbol
;; COPYRIGHT   : (C) 2026  Massimiliano Gubinelli
;;
;; This software falls under the GNU general public license version 3 or later.
;; It comes WITHOUT ANY WARRANTY WHATSOEVER. For details, see the file LICENSE
;; in the root directory or <http://www.gnu.org/licenses/gpl-3.0.html>.
;;
;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;;

(texmacs-module (language unicode-names))

;; Generated by tests/opentype/unicode-names.py from the conversion tables of
;; TeXmacs/langs/encoding and the Unicode database; do not edit by hand. The
;; balloon of a symbol button says what is here, see make-menu-symbol in
;; kernel/gui/menu-widget.scm.

(define-table unicode-symbol-name-table
'''

TAIL = '''\
)

(tm-define (unicode-symbol-name sym)
  (:synopsis "The code point and the Unicode name of a symbol, or the empty string")
  (with r (ahash-ref unicode-symbol-name-table sym)
    (if r (car r) "")))
'''

def main ():
    ap = argparse.ArgumentParser ()
    ap.add_argument ("-o", "--output", default = os.path.join (
        top (), "TeXmacs", "progs", "language", "unicode-names.scm"))
    args = ap.parse_args ()
    codes = load_codes ()
    lines = []
    for sym in sorted (codes, key = lambda s: (codes[s], s)):
        lines.append ('  ("%s" "%s")' % (sym, describe (codes[sym])))
    with open (args.output, "w") as f:
        f.write (HEAD + "\n".join (lines) + "\n" + TAIL)
    print ("%d symbols -> %s" % (len (lines), args.output))

main ()
