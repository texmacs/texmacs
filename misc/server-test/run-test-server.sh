#!/bin/bash

# run-test-server.sh — start server and wait for readiness
set -euo pipefail
cd "$(dirname "$0")"

PORT=6561
TIMEOUT=30

make fixtures

# Start containers
docker compose up -d --build

# Wait for server to be listening
echo "Waiting for server on port $PORT..."
for i in $(seq 1 "$TIMEOUT"); do
  if docker compose exec -T texmacs-server sh -c "ss -tln | grep -q ':${PORT} '" 2>/dev/null; then
    echo "Server ready (${i}s)"
    break
  fi
  if [ "$i" -eq "$TIMEOUT" ]; then
    echo "Server failed to start within ${TIMEOUT}s"
    docker compose logs texmacs-server
    exit 1
  fi
  sleep 1
done

# Wait for TLS cert to appear (generated by fixtures on server on startup)
echo "Waiting for TLS certificate..."
for i in $(seq 1 "$TIMEOUT"); do
  if [ -f certs/cert.pem ]; then
    echo "Certificate ready (${i}s)"
    break
  fi
  if [ "$i" -eq "$TIMEOUT" ]; then
    echo "Certificate not generated within ${TIMEOUT}s"
    docker compose logs texmacs-server
    exit 1
  fi
  sleep 1
done

echo "Server is up and ready on port $PORT"
